"""Deterministic audio cue packer for the Godot 4 asset vault.

Reads a cue sheet, processes source WAVs into normalized Godot-ready clips,
and emits an AudioBusLayout, a GDScript cue registry, and a JSON manifest.

AI/agents decide *what* cues should exist; this module deterministically
produces them. Same sheet + same sources always yield the same bytes.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import math
import sys
import wave
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_CUE_SHEET = ROOT / "audio" / "cue_sheet.json"
LICENSES_MD_PATH = ROOT / "THIRD_PARTY_LICENSES.md"
AUDIO_SECTION_START = "<!-- AUDIO_START -->"
AUDIO_SECTION_END = "<!-- AUDIO_END -->"


def load_wav(path: Path) -> tuple[np.ndarray, int, int]:
    with wave.open(str(path), "rb") as wf:
        if wf.getsampwidth() != 2:
            raise ValueError(f"Only 16-bit PCM WAV supported: {path}")
        rate = wf.getframerate()
        channels = wf.getnchannels()
        raw = wf.readframes(wf.getnframes())
    pcm = np.frombuffer(raw, dtype="<i2").astype(np.float32) / 32768.0
    if channels > 1:
        pcm = pcm.reshape(-1, channels)
    return pcm, rate, channels


def write_wav(path: Path, audio: np.ndarray, rate: int) -> None:
    pcm = np.clip(audio, -1.0, 1.0)
    pcm = np.rint(pcm * 32767.0).astype("<i2")
    with wave.open(str(path), "wb") as wf:
        wf.setnchannels(1 if pcm.ndim == 1 else pcm.shape[1])
        wf.setsampwidth(2)
        wf.setframerate(rate)
        wf.writeframes(pcm.tobytes())


def db_to_linear(db: float) -> float:
    return 10.0 ** (db / 20.0)


def linear_to_db(value: float) -> float:
    return 20.0 * math.log10(max(value, 1e-9))


def process_cue(audio: np.ndarray, rate: int, target_peak_db: float, fade_ms: int, loop: bool) -> np.ndarray:
    out = np.array(audio, dtype=np.float32, copy=True)
    peak = float(np.max(np.abs(out))) if out.size else 0.0
    if peak > 0.0:
        out *= db_to_linear(target_peak_db) / peak

    if not loop and fade_ms > 0:
        frames = int(rate * fade_ms / 1000.0)
        frames = min(frames, max(1, len(out) // 2))
        ramp = np.linspace(0.0, 1.0, frames, dtype=np.float32)
        if out.ndim == 1:
            out[:frames] *= ramp
            out[-frames:] *= ramp[::-1]
        else:
            out[:frames, :] *= ramp[:, None]
            out[-frames:, :] *= ramp[::-1, None]
    return np.clip(out, -1.0, 1.0)


def write_bus_layout(path: Path, buses: list[dict]) -> None:
    lines = ['[gd_resource type="AudioBusLayout" format=3]', "", "[resource]"]
    for idx, bus in enumerate(buses, start=1):
        name = str(bus["name"])
        lines += [
            f'bus/{idx}/name = &"{name}"',
            f"bus/{idx}/solo = {str(bool(bus.get('solo', False))).lower()}",
            f"bus/{idx}/mute = {str(bool(bus.get('mute', False))).lower()}",
            f"bus/{idx}/bypass_fx = {str(bool(bus.get('bypass_fx', False))).lower()}",
            f"bus/{idx}/volume_db = {float(bus.get('volume_db', 0.0))}",
            f'bus/{idx}/send = &"{bus.get("send", "Master")}"',
        ]
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def write_cue_registry(path: Path, pack: str, out_rel: str, cues: list[dict]) -> None:
    entries = []
    for cue in cues:
        entries.append(
            f'\t"{cue["id"]}": {{\n'
            f'\t\t"path": "res://{out_rel}/{cue["id"]}.wav",\n'
            f'\t\t"bus": "{cue["bus"]}",\n'
            f'\t\t"role": "{cue["role"]}",\n'
            f'\t\t"duration": {cue["duration"]},\n'
            f"\t}},"
        )
    body = "\n".join(entries)
    source = (
        "# Generated by tools/pack_audio_assets.py - do not edit.\n"
        f"# Pack: {pack}\n\n"
        "extends Node\n\n"
        f'const PACK := "{pack}"\n'
        "const CUES := {\n"
        f"{body}\n"
        "}\n\n"
        "static func has_cue(id: StringName) -> bool:\n"
        "\treturn CUES.has(String(id))\n\n"
        "static func stream_for(id: StringName) -> AudioStream:\n"
        "\tvar key := String(id)\n"
        "\tif not CUES.has(key):\n"
        "\t\treturn null\n"
        '\tvar path := String(CUES[key]["path"])\n'
        "\tif not ResourceLoader.exists(path):\n"
        "\t\treturn null\n"
        "\treturn load(path) as AudioStream\n"
    )
    path.write_text(source, encoding="utf-8")


def update_license_section(records: list[dict]) -> None:
    if not records:
        return
    lines = [
        AUDIO_SECTION_START,
        "## Audio Cues",
        "",
        "| Cue | Role | License | Source | Bus |",
        "| :--- | :--- | :--- | :--- | :--- |",
    ]
    for rec in records:
        lines.append(
            f'| `{rec["id"]}` | {rec["role"]} | {rec["license"]} | '
            f'{rec["source_url"]} | {rec["bus"]} |'
        )
    lines.append(AUDIO_SECTION_END)
    block = "\n".join(lines) + "\n"

    existing = LICENSES_MD_PATH.read_text(encoding="utf-8") if LICENSES_MD_PATH.exists() else "# Third-Party Licenses\n\n"
    if AUDIO_SECTION_START in existing and AUDIO_SECTION_END in existing:
        import re

        existing = re.sub(
            rf"{re.escape(AUDIO_SECTION_START)}.*?{re.escape(AUDIO_SECTION_END)}\n?",
            block,
            existing,
            flags=re.DOTALL,
        )
    else:
        existing = existing.rstrip() + "\n\n" + block
    LICENSES_MD_PATH.write_text(existing, encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description="Pack audio cues into Godot-ready WAVs and resources.")
    parser.add_argument("--cue-sheet", type=Path, default=DEFAULT_CUE_SHEET)
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()

    if not args.cue_sheet.exists():
        print(f"MISSING: {args.cue_sheet}", file=sys.stderr)
        return 1

    sheet = json.loads(args.cue_sheet.read_text(encoding="utf-8"))
    pack = sheet["pack"]
    source_dir = ROOT / sheet["source_dir"]
    out_rel = sheet["output_dir"]
    out_dir = ROOT / out_rel
    buses = sheet.get("buses", [])
    cues = sheet.get("cues", [])

    if args.dry_run:
        for cue in cues:
            src = source_dir / cue["source"]
            print(f'{"OK" if src.exists() else "MISSING"}: {cue["id"]} <- {src}')
        print(f"DRY RUN: {len(cues)} cues, {len(buses)} buses")
        return 0

    out_dir.mkdir(parents=True, exist_ok=True)
    records: list[dict] = []

    for cue in cues:
        src = source_dir / cue["source"]
        if not src.exists():
            print(f"MISSING: {src}", file=sys.stderr)
            return 1
        audio, rate, channels = load_wav(src)
        processed = process_cue(
            audio,
            rate,
            float(cue.get("target_peak_db", -1.5)),
            int(cue.get("fade_ms", 3)),
            bool(cue.get("loop", False)),
        )
        target = out_dir / f'{cue["id"]}.wav'
        write_wav(target, processed, rate)

        digest = hashlib.sha256(target.read_bytes()).hexdigest()[:16]
        record = {
            "id": cue["id"],
            "source": f'{sheet["source_dir"]}/{cue["source"]}',
            "target": f'{out_rel}/{cue["id"]}.wav',
            "role": cue["role"],
            "bus": cue["bus"],
            "loop": bool(cue.get("loop", False)),
            "sample_rate": rate,
            "channels": channels,
            "duration": round(len(processed) / rate, 4),
            "peak_db": round(linear_to_db(float(np.max(np.abs(processed)))), 2),
            "rms_db": round(linear_to_db(float(np.sqrt(np.mean(np.square(processed))))), 2),
            "sha256_16": digest,
            "license": cue.get("license", "CC0-1.0"),
            "source_url": cue.get("source_url", "local procedural generation"),
        }
        records.append(record)
        print(f'PACKED: {cue["id"]} -> {record["target"]} ({record["duration"]}s, {record["peak_db"]} dBFS)')

    write_bus_layout(out_dir / "audio_bus_layout.tres", buses)
    write_cue_registry(out_dir / "audio_cue_registry.gd", pack, out_rel, records)

    manifest = {
        "pack": pack,
        "cue_sheet": str(args.cue_sheet.relative_to(ROOT)),
        "cue_sheet_sha256": hashlib.sha256(args.cue_sheet.read_bytes()).hexdigest()[:16],
        "buses": buses,
        "cues": records,
    }
    manifest_path = out_dir / "audio_manifest.json"
    manifest_path.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    update_license_section(records)
    print(f"UPDATED: {manifest_path} ({len(records)} cues)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
